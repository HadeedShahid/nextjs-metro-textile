/**
 * One-off generator for the Global Presence silver map.
 *
 * Fetches Natural Earth 110m country geometry, projects an Asia-centred crop
 * into a fixed viewBox, and bakes the country outlines + pin coordinates into
 * components/presenceMapPaths.ts — so the site ships plain SVG paths with no
 * map library at runtime.
 *
 * Re-run with: node scripts/generate-presence-map.mjs
 */
import { writeFileSync } from "node:fs";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature } from "topojson-client";

// Wide banner strip sitting under the company cards.
const VB = { w: 960, h: 320 };

// Asia crop window (lon/lat). The cover-fit below scales this up until it
// fills the viewBox, so the exact aspect here only sets what stays in frame.
const WINDOW = {
  type: "Polygon",
  coordinates: [[[46, 54], [140, 54], [140, 0], [46, 0], [46, 54]]],
};

const PINS = {
  Pakistan: [69.3, 30.4],
  China: [104.2, 35.9],
  "Hong Kong": [114.1, 22.3],
};

const world = await fetch(
  "https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json",
).then((r) => r.json());

const countries = feature(world, world.objects.countries);

const projection = geoNaturalEarth1().fitSize([VB.w, VB.h], WINDOW);

// fitSize letterboxes (contain). Scale up until the window covers the viewBox
// instead, then recentre — the CSS equivalent of object-fit: cover, resolved
// at build time so the baked paths always fill the frame.
{
  const bounds = geoPath(projection).bounds(WINDOW);
  const bw = bounds[1][0] - bounds[0][0];
  const bh = bounds[1][1] - bounds[0][1];
  const cover = Math.max(VB.w / bw, VB.h / bh);
  if (cover > 1.0001) {
    projection.scale(projection.scale() * cover);
    const b2 = geoPath(projection).bounds(WINDOW);
    const [tx, ty] = projection.translate();
    projection.translate([
      tx + (VB.w - (b2[1][0] + b2[0][0])) / 2,
      ty + (VB.h - (b2[1][1] + b2[0][1])) / 2,
    ]);
  }
}

// Clip geometry to the viewBox so off-screen countries vanish and partially
// visible ones are cut down to their visible slice.
projection.clipExtent([
  [-2, -2],
  [VB.w + 2, VB.h + 2],
]);
const path = geoPath(projection);

const paths = countries.features
  .map((f) => path(f))
  // Drop empty results and micro-islands that read as specks at this size.
  .filter((d) => d && d.length > 40)
  // Integer coordinates — sub-pixel precision is invisible at this scale.
  .map((d) => d.replace(/\d+\.\d+/g, (n) => Math.round(Number(n))));

const pins = Object.fromEntries(
  Object.entries(PINS).map(([name, lonlat]) => {
    const [x, y] = projection(lonlat);
    return [name, [Math.round(x * 10) / 10, Math.round(y * 10) / 10]];
  }),
);

const out = `// Generated by scripts/generate-presence-map.mjs — do not edit by hand.
// Natural Earth 110m geometry, Asia-centred crop, viewBox ${VB.w}x${VB.h}.

export const MAP_VB = { w: ${VB.w}, h: ${VB.h} } as const;

export const PIN_COORDS: Record<string, readonly [number, number]> = ${JSON.stringify(pins, null, 2)};

export const COUNTRY_PATHS: readonly string[] = ${JSON.stringify(paths, null, 2)};
`;

writeFileSync(new URL("../components/presenceMapPaths.ts", import.meta.url), out);
console.log(
  `wrote ${paths.length} country paths, pins:`,
  Object.entries(pins)
    .map(([k, v]) => `${k}@${v}`)
    .join("  "),
);
